def trim_switch_source_notch_fills() -> list[tuple[float, float, float, float]]:
    """Return same-net M1 fills between switch S columns and escapes."""
    floorplan = json.loads((ROOT / "v2/layout/floorplan.json").read_text())
    template = json.loads((ROOT / "v2/layout/channel_template.json").read_text())
    switches = [
        component for component in template["components"]
        if component["name"].startswith("TSW")
    ]
    fills: list[tuple[float, float, float, float]] = []
    for channel in floorplan["channels"]:
        channel_x = float(channel["center_x"])
        for switch in switches:
            terminal_x = channel_x + float(switch["x"]) + 0.22
            fills.append((
                terminal_x + 0.115,
                45.87,
                terminal_x + 0.185,
                46.50,
            ))
    if len(fills) != 32:
        raise ValueError(f"expected 32 trim switch notch fills, got {len(fills)}")
    return fills


def same_net_neck_fills() -> dict[tuple[int, int], list[tuple[float, float, float, float]]]:
    """Return local fills for connected, same-net re-entrant route necks.

    Every rectangle is derived from a repeated route-generator junction.  No
    fill crosses between distinct nets: it only widens the narrow bridge that
    already joins the two conductor lobes.
    """
    floorplan = json.loads((ROOT / "v2/layout/floorplan.json").read_text())
    channels = [float(item["center_x"]) for item in floorplan["channels"]]
    m1: list[tuple[float, float, float, float]] = []
    m2: list[tuple[float, float, float, float]] = []
    m3: list[tuple[float, float, float, float]] = []

    # Three terminal-to-access M1 ladders per channel have a legal 230 nm
    # bridge between wider terminal/via pads, but leave a 60 nm deep notch.
    for channel_index, channel_x in enumerate(channels):
        middle_offset = 1.71 if channel_index in (0, 1) else 2.50
        for offset in (-1.95, middle_offset, 4.58):
            center_x = channel_x + offset
            m1.append((center_x - 0.145, 44.58,
                       center_x + 0.145, 44.64))

        # Phase-enable via2 landings meet their M2 pin escapes at the upper
        # edge.  Fill the 40 nm-deep same-net shoulders at both polarities.
        m2.extend((
            (channel_x - 3.275, 121.60, channel_x - 3.20, 121.64),
            (channel_x + 5.040, 121.60, channel_x + 5.115, 121.64),
            # Do not fill the former 47.245/47.405 um trim-control notches:
            # they lie between the true and complementary bit-1/bit-3 gates.
            # Filling them shorts inverter input to output.  Likewise, the
            # former 73/78 um mixer fills short gm_p to gm_n.
            (channel_x + 1.120, 43.960, channel_x + 1.155, 44.000),
        ))
        # The phase-select M3 T junction changes its left edge by 200 nm in
        # two consecutive 200 nm-high slabs.  Widen the lower slab to the
        # existing vertical edge so the same-net junction is 400 nm wide.
        phase0_x = channel_x - 3.40
        m3.append((phase0_x - 0.20, 128.50, phase0_x, 128.70))

    # Both terminals of each bias diode are explicitly assigned to VGND.
    # Their M2 ground branches are already joined above/below these slots.
    for center_x in (167.5, 177.5):
        m2.extend((
            (center_x + 0.160, 95.570, center_x + 0.195, 95.610),
            (center_x - 0.195, 97.390, center_x - 0.160, 97.430),
        ))

    return {MET1: m1, MET2: m2, MET3: m3}


def local_clearance_cuts(
    landing_orientations: dict[tuple[int, int], str],
) -> dict[tuple[int, int], list[tuple[float, float, float, float]]]:
    """Return local removals that increase spacing between distinct nets."""
    cuts: dict[tuple[int, int], list[tuple[float, float, float, float]]] = {
        MET2: [],
        MET3: [],
    }
    # The two mux signals at each dense pair are distinct nets.  Trim only
    # the route shoulder beyond the already-legal directional VIA1 landing.
    for (cx_nm, cy_nm), orientation in landing_orientations.items():
        cx, cy = cx_nm / 1000, cy_nm / 1000
        if orientation == "dense_e":
            cuts[MET2].append((cx + 0.130, cy - 0.160,
                               cx + 0.160, cy + 0.160))
        elif orientation == "dense_w":
            cuts[MET2].append((cx - 0.160, cy - 0.160,
                               cx - 0.130, cy + 0.160))

    floorplan = json.loads((ROOT / "v2/layout/floorplan.json").read_text())
    for channel in floorplan["channels"]:
        channel_x = float(channel["center_x"])
        # At each LO branch, remove the 60 nm outer shoulder of a 620 nm M3
        # via2 landing.  The remaining 560 nm landing retains at least
        # 150 nm enclosure around its 200 nm via2 and aligns with its 500 nm
        # vertical conductor, while giving the unrelated LO spine 300 nm.
        cuts[MET3].extend((
            (channel_x - 3.290, 80.800,
             channel_x - 3.230, 81.200),
            (channel_x + 5.070, 76.100,
             channel_x + 5.130, 76.500),
        ))
        # Complementary trim-control routes are distinct nets.  Shorten only
        # their terminal-free M2 endpoints to obtain 140 nm spacing; the old
        # repair filled these gaps and shorted inverter input to output.
        cuts[MET2].extend((
            (channel_x - 0.785, 47.245,
             channel_x - 0.765, 47.565),
            (channel_x + 2.605, 47.245,
             channel_x + 2.730, 47.565),
        ))
    # Remove the old 400 nm M2 landing area for each shifted mixer VIA2.  The
    # original horizontal 320 nm route continues outside this window; a new
    # landing is added 300 nm inward and overlaps that unchanged route.
    for (cx_nm, cy_nm) in mixer_via2_relocations():
        cx, cy = cx_nm / 1000, cy_nm / 1000
        cuts[MET2].append((cx - 0.20, cy - 0.20,
                           cx + 0.20, cy + 0.20))
    return cuts


def mixer_via2_relocations() -> dict[tuple[int, int], tuple[int, int]]:
    """Move two B-row GM transitions away from the opposite GM terminal.

    The original 20 nm M2 gaps at 73.6 and 78.3 um cannot be repaired with
    fill: doing so shorts gm_p to gm_n.  Moving only the M2-to-M3 transition
    300 nm inward leaves every terminal ladder and vertical GM spine fixed;
    a short same-net M3 bridge reconnects the shifted landing to its spine.
    """
    floorplan = json.loads((ROOT / "v2/layout/floorplan.json").read_text())
    relocations: dict[tuple[int, int], tuple[int, int]] = {}
    for channel in floorplan["channels"]:
        channel_x_nm = round(float(channel["center_x"]) * 1000)
        relocations[(channel_x_nm - 80, 73600)] = (300, 0)
        relocations[(channel_x_nm + 1920, 78300)] = (-300, 0)
    if len(relocations) != 8:
        raise ValueError(f"expected 8 mixer VIA2 relocations, got {len(relocations)}")
    return relocations


def boundary_rectangles(
    element: list[bytes], database_um: float,
) -> list[tuple[float, float, float, float]]:
    xy_records = [record for record in element if record_type(record) == XY]
    if len(xy_records) != 1:
        raise ValueError(f"boundary has {len(xy_records)} XY records")
    payload = xy_records[0][4:]
    values = struct.unpack(f">{len(payload) // 4}i", payload)
    points = list(zip(values[0::2], values[1::2]))
    return orthogonal_polygon_rectangles(points, database_um)


def subtract_cut(
    rectangle: tuple[float, float, float, float],
    cut: tuple[float, float, float, float],
) -> list[tuple[float, float, float, float]]:
    """Subtract one axis-aligned cut from one rectangle."""
    lx, by, rx, ty = rectangle
    clx, cby, crx, cty = cut
    ilx, iby = max(lx, clx), max(by, cby)
    irx, ity = min(rx, crx), min(ty, cty)
    if irx <= ilx + 1e-12 or ity <= iby + 1e-12:
        return [rectangle]
    pieces = [
        (lx, by, ilx, ty),
        (irx, by, rx, ty),
        (ilx, by, irx, iby),
        (ilx, ity, irx, ty),
    ]
    return [
        piece for piece in pieces
        if piece[2] > piece[0] + 1e-12 and piece[3] > piece[1] + 1e-12
    ]


def rectangle_boundary(
    layer: tuple[int, int], bbox_um: tuple[float, float, float, float]
) -> list[bytes]:
    lx, by, rx, ty = (round(value * 1000) for value in bbox_um)
    points = (lx, by, rx, by, rx, ty, lx, ty, lx, by)
    return [
        make_record(BOUNDARY, 0x00),
        make_record(LAYER, 0x02, struct.pack(">h", layer[0])),
        make_record(DATATYPE, 0x02, struct.pack(">h", layer[1])),
        make_record(XY, INT4, struct.pack(">10i", *points)),
        make_record(ENDEL, 0x00),
    ]


def replace_boundary_bbox(
    element: list[bytes], bbox_um: tuple[float, float, float, float]
) -> list[bytes]:
    lx, by, rx, ty = (round(value * 1000) for value in bbox_um)
    points = (lx, by, rx, by, rx, ty, lx, ty, lx, by)
    return [
        make_record(XY, INT4, struct.pack(">10i", *points))
        if record_type(record) == XY else record
        for record in element
    ]


def remove_unused_trim_nfet_gate_bars(source: bytes) -> tuple[bytes, list[str]]:
    """Remove optional PCell gate-bar M1/MCON; routed gate contact remains."""
    header, structures, endlib = split_library(records(source))
    rewritten: list[list[bytes]] = []
    repaired: list[str] = []
    for structure in structures:
        name = structure_name(structure)
        if name not in TRIM_NFET_GATE_BAR_CELLS:
            rewritten.append(structure)
            continue
        replacement: list[bytes] = []
        index = 0
        while index < len(structure):
            if record_type(structure[index]) != BOUNDARY:
                replacement.append(structure[index])
                index += 1
                continue
            end = index
            while record_type(structure[end]) != ENDEL:
                end += 1
            element = structure[index : end + 1]
            layer = element_layer(element)
            if layer in (MET1, MCON):
                lx, by, rx, ty = element_bbox(element, 0.001)
                center_y = (by + ty) / 2.0
                remove_gate_bar = (
                    center_y < -0.70
                    if name == "sky130_fd_pr__nfet_01v8_WSWNGM"
                    else abs(center_y) > 0.70
                )
                if remove_gate_bar:
                    element = []
            replacement.extend(element)
            index = end + 1
        rewritten.append(replacement)
        repaired.append(name)
    if set(repaired) != TRIM_NFET_GATE_BAR_CELLS:
        missing = sorted(TRIM_NFET_GATE_BAR_CELLS - set(repaired))
        raise ValueError(f"trim NFET masters absent: {missing}")
    output = b"".join(header)
    output += b"".join(record for structure in rewritten for record in structure)
    output += endlib
    return output, sorted(repaired)


def remove_power_overlay_bridge_mcons(source: bytes) -> tuple[bytes, int]:
    """Remove four overlay MCONs already provided by resistor terminals."""
    header, structures, endlib = split_library(records(source))
    rewritten_structures: list[list[bytes]] = []
    removed = 0
    for structure in structures:
        if structure_name(structure) != "v2_control_power_overlay":
            rewritten_structures.append(structure)
            continue
        rewritten: list[bytes] = []
        index = 0
        while index < len(structure):
            if record_type(structure[index]) != BOUNDARY:
                rewritten.append(structure[index])
                index += 1
                continue
            end = index
            while record_type(structure[end]) != ENDEL:
                end += 1
            element = structure[index : end + 1]
            if element_layer(element) == MCON:
                removed += 1
            else:
                rewritten.extend(element)
            index = end + 1
        rewritten_structures.append(rewritten)
    if removed != 4:
        raise ValueError(
            f"v2_control_power_overlay has {removed} bridge MCONs, expected 4"
        )
    output = b"".join(header)
    output += b"".join(
        record for structure in rewritten_structures for record in structure
    )
    output += endlib
    return output, removed


def replace_varactor_master(source: bytes) -> tuple[bytes, dict[str, object]]:
    """Restore the guarded varactor regenerated with legal guard clearance.

    The stock Magic generator uses ``dev_sub_dist=0.14`` for this LVT
    varactor, which becomes eight ``varac.5`` errors after GDS re-import.
    The vendored master was generated by the same pinned PDK with only that
    clearance changed to 0.30 um.  Device poly/diffusion/N-well and the
    17.68 x 17.68 um electrical parameters are unchanged; the grounded guard
    ring moves outward by 0.16 um.
    """
    master_data = VARACTOR_MASTER.read_bytes()
    master_hash = hashlib.sha256(master_data).hexdigest()
    if master_hash != VARACTOR_MASTER_SHA256:
        raise ValueError(
            f"varactor master hash {master_hash} != {VARACTOR_MASTER_SHA256}"
        )
    source_records = records(source)
    master_records = records(master_data)
    if unit_record(source_records) != unit_record(master_records):
        raise ValueError("varactor master GDS units differ from source")
    header, structures, endlib = split_library(source_records)
    _, master_structures, _ = split_library(master_records)
    masters = {
        structure_name(structure): structure for structure in master_structures
    }
    if VARACTOR_CELL not in masters:
        raise ValueError(f"vendored GDS lacks {VARACTOR_CELL}")
    replacement = masters[VARACTOR_CELL]
    rewritten_structures: list[list[bytes]] = []
    changed = identical = 0
    for structure in structures:
        if structure_name(structure) != VARACTOR_CELL:
            rewritten_structures.append(structure)
        elif structure == replacement:
            rewritten_structures.append(structure)
            identical += 1
        else:
            rewritten_structures.append(replacement)
            changed += 1
    if changed + identical != 1:
        raise ValueError(
            f"found {changed + identical} source varactor masters, expected 1"
        )
    output = b"".join(header)
    output += b"".join(
        record for structure in rewritten_structures for record in structure
    )
    output += endlib
    return output, {
        "status": "pass",
        "master": str(VARACTOR_MASTER.relative_to(ROOT)),
        "master_sha256": master_hash,
        "replaced": changed,
        "already_identical": identical,
        "generator_change": {"dev_sub_dist_um": {"from": 0.14, "to": 0.30}},
    }


def extend_legal_varactor_nwell(source: bytes) -> tuple[bytes, int]:
    """Extend the well after the guard has been moved safely outward."""
    header, structures, endlib = split_library(records(source))
    output_structures: list[list[bytes]] = []
    changed = 0
    for structure in structures:
        if structure_name(structure) != VARACTOR_CELL:
            output_structures.append(structure)
            continue
        rewritten: list[bytes] = []
        index = 0
        while index < len(structure):
            if record_type(structure[index]) != BOUNDARY:
                rewritten.append(structure[index])
                index += 1
                continue
            end = index
            while record_type(structure[end]) != ENDEL:
                end += 1
            element = structure[index : end + 1]
            if element_layer(element) == NWELL:
                bbox = tuple(round(value, 3) for value in element_bbox(element, 0.001))
                if bbox != (-9.505, -9.295, 9.505, 9.295):
                    raise ValueError(f"unexpected legal varactor N-well {bbox}")
                element = replace_boundary_bbox(
                    element, (-9.505, -9.430, 9.505, 9.430)
                )
                changed += 1
            rewritten.extend(element)
            index = end + 1
        output_structures.append(rewritten)
    if changed != 1:
        raise ValueError(f"extended {changed} legal varactor N-wells, expected 1")
    output = b"".join(header)
    output += b"".join(
        record for structure in output_structures for record in structure
    )
    output += endlib
    return output, changed


def element_layer(element: list[bytes]) -> tuple[int, int] | None:
    layer = datatype = None
    for record in element:
        if record_type(record) == LAYER:
            layer = struct.unpack(">h", record[4:])[0]
        elif record_type(record) == DATATYPE:
            datatype = struct.unpack(">h", record[4:])[0]
    if layer is None or datatype is None:
        return None
    return layer, datatype


def element_bbox(element: list[bytes], database_um: float) -> tuple[float, float, float, float]:
    xy_records = [record for record in element if record_type(record) == XY]
    if len(xy_records) != 1:
        raise ValueError(f"boundary has {len(xy_records)} XY records")
    payload = xy_records[0][4:]
    values = struct.unpack(f">{len(payload) // 4}i", payload)
    xs = [value * database_um for value in values[0::2]]
    ys = [value * database_um for value in values[1::2]]
    return min(xs), min(ys), max(xs), max(ys)


def child_rectangles(source_path: Path, top: str, wanted: tuple[int, int]) -> list[tuple[float, float, float, float]]:
    structures, database_um = parse_gds(source_path)
    output: list[tuple[float, float, float, float]] = []

    def visit(name: str, matrix: tuple[float, float, float, float, float, float]) -> None:
        structure = structures[name]
        for layer, polygon in structure.polygons:
            if layer != wanted:
                continue
            transformed = [transform(matrix, point) for point in polygon]
            output.extend(orthogonal_polygon_rectangles(transformed, database_um))
        for reference in structure.references:
            visit(reference.name, compose(matrix, reference_matrix(reference)))

    for reference in structures[top].references:
        visit(reference.name, reference_matrix(reference))
    return output


def point_covered(
    point: tuple[float, float], rectangles: list[tuple[float, float, float, float]]
) -> bool:
    x, y = point
    return any(
        lx - 1e-9 <= x <= rx + 1e-9 and by - 1e-9 <= y <= ty + 1e-9
        for lx, by, rx, ty in rectangles
    )


def filter_top_boundaries(
    source: bytes,
    top: str,
    database_um: float,
    redundant_mcon_centers: set[tuple[int, int]],
    via1_centers: set[tuple[int, int]],
    retained_mcon_centers: set[tuple[int, int]],
    landing_orientations: dict[tuple[int, int], str],
    landing_relocations: dict[tuple[int, int], tuple[int, int]],
) -> tuple[bytes, int, int, int, int, int]:
    header, structures, endlib = split_library(records(source))
    rewritten_structures: list[list[bytes]] = []
    removed = 0
    removed_m1_landings = 0
    narrowed = 0
    relocated_via1 = 0
    relocated_mixer_via2_shapes = 0
    clearance_trimmed = 0
    cuts_by_layer = local_clearance_cuts(landing_orientations)
    via2_relocations = mixer_via2_relocations()
    for structure in structures:
        if structure_name(structure) != top:
            rewritten_structures.append(structure)
            continue
        rewritten: list[bytes] = []
        added: list[bytes] = []
        for bbox in trim_switch_source_notch_fills():
            added.extend(rectangle_boundary(MET1, bbox))
        for layer, bboxes in same_net_neck_fills().items():
            for bbox in bboxes:
                added.extend(rectangle_boundary(layer, bbox))
        for (cx_nm, cy_nm), (dx_nm, dy_nm) in landing_relocations.items():
            cx_um, cy_um = cx_nm / 1000, cy_nm / 1000
            nx_um = cx_um + dx_nm / 1000
            ny_um = cy_um + dy_nm / 1000
            south_half = (
                0.130
                if cy_nm == 47405 and dx_nm == 105 and dy_nm == 0
                else 0.160
            )
            added.extend(rectangle_boundary(
                MET1,
                (nx_um - 0.16, ny_um - south_half,
                 nx_um + 0.16, ny_um + 0.16),
            ))
            if dx_nm:
                bridge = (
                    min(cx_um, nx_um), cy_um - 0.115,
                    max(cx_um, nx_um), cy_um + 0.115,
                )
            else:
                bridge = (
                    cx_um - 0.115, min(cy_um, ny_um),
                    cx_um + 0.115, max(cy_um, ny_um),
                )
            added.extend(rectangle_boundary(MET1, bridge))
            added.extend(rectangle_boundary((69, 20), bridge))
            added.extend(rectangle_boundary(
                (69, 20),
                (nx_um - 0.16, ny_um - 0.16,
                 nx_um + 0.16, ny_um + 0.16),
            ))
        for (cx_nm, cy_nm), orientation in landing_orientations.items():
            if orientation == "short_s" and cy_nm in {32300, 35440, 38580}:
                cx_um, cy_um = cx_nm / 1000, cy_nm / 1000
                # The narrowed gate landing clears the diagonal neighbor but
                # would leave a 30 nm gap to its own horizontal gate escape.
                # A central 230 nm same-net bridge reconnects that escape
                # without restoring the illegal landing corners.
                added.extend(rectangle_boundary(
                    MET1,
                    (cx_um - 0.115, cy_um - 0.160,
                     cx_um + 0.115, cy_um - 0.130),
                ))
        for (cx_nm, cy_nm), (dx_nm, dy_nm) in via2_relocations.items():
            cx_um, cy_um = cx_nm / 1000, cy_nm / 1000
            nx_um = cx_um + dx_nm / 1000
            added.extend(rectangle_boundary(
                MET2,
                (nx_um - 0.20, cy_um - 0.20,
                 nx_um + 0.20, cy_um + 0.20),
            ))
            added.extend(rectangle_boundary(
                MET3,
                (nx_um - 0.31, cy_um - 0.20,
                 nx_um + 0.31, cy_um + 0.20),
            ))
            # The shifted M3 landing is joined back to the unchanged vertical
            # GM spine.  This bridge is on one named GM net only.
            added.extend(rectangle_boundary(
                MET3,
                (min(cx_um, nx_um), cy_um - 0.20,
                 max(cx_um, nx_um), cy_um + 0.20),
            ))
        index = 0
        while index < len(structure):
            if record_type(structure[index]) != BOUNDARY:
                rewritten.append(structure[index])
                index += 1
                continue
            end = index
            while record_type(structure[end]) != ENDEL:
                end += 1
            element = structure[index : end + 1]
            remove = False
            if element_layer(element) == MCON:
                lx, by, rx, ty = element_bbox(element, database_um)
                center_nm = (
                    round((lx + rx) * 500),
                    round((by + ty) * 500),
                )
                remove = center_nm in redundant_mcon_centers
            if remove:
                removed += 1
            else:
                layer = element_layer(element)
                if layer == VIA2:
                    lx, by, rx, ty = element_bbox(element, database_um)
                    center_nm = (
                        round((lx + rx) * 500),
                        round((by + ty) * 500),
                    )
                    delta_nm = via2_relocations.get(center_nm)
                    dimensions_nm = (
                        round((rx - lx) * 1000),
                        round((ty - by) * 1000),
                    )
                    if delta_nm and dimensions_nm == (200, 200):
                        dx_nm, dy_nm = delta_nm
                        element = replace_boundary_bbox(
                            element,
                            (
                                lx + dx_nm / 1000, by + dy_nm / 1000,
                                rx + dx_nm / 1000, ty + dy_nm / 1000,
                            ),
                        )
                        relocated_mixer_via2_shapes += 1
                if layer == VIA1:
                    lx, by, rx, ty = element_bbox(element, database_um)
                    center_nm = (
                        round((lx + rx) * 500),
                        round((by + ty) * 500),
                    )
                    delta_nm = landing_relocations.get(center_nm)
                    if delta_nm:
                        dx_nm, dy_nm = delta_nm
                        element = replace_boundary_bbox(
                            element,
                            (
                                lx + dx_nm / 1000,
                                by + dy_nm / 1000,
                                rx + dx_nm / 1000,
                                ty + dy_nm / 1000,
                            ),
                        )
                        relocated_via1 += 1
                if element_layer(element) == MET1:
                    lx, by, rx, ty = element_bbox(element, database_um)
                    center_nm = (
                        round((lx + rx) * 500),
                        round((by + ty) * 500),
                    )
                    width_nm = round((rx - lx) * 1000)
                    height_nm = round((ty - by) * 1000)
                    # li_to_m1_stack() used to paint a second 290 x 230 nm
                    # M1 landing and MCON on every measured LI terminal.  If
                    # the child already has native M1 at that MCON center,
                    # both shapes are redundant.  Remove only that exact
                    # generator signature.  A real M1 route leaving the
                    # terminal remains in place, as do all VIA1 landings.
                    if (
                        center_nm in redundant_mcon_centers
                        and (width_nm, height_nm) == (290, 230)
                        and center_nm not in landing_relocations
                    ):
                        removed_m1_landings += 1
                        element = []
                    delta_nm = landing_relocations.get(center_nm)
                    if (
                        delta_nm
                        and (width_nm, height_nm) == (320, 320)
                        and center_nm in via1_centers
                    ):
                        dx_nm, dy_nm = delta_nm
                        element = []
                    # A centered 150 nm VIA1 needs 55 nm M1 enclosure on all
                    # sides and 85 nm on two adjacent sides.  260 x 320 nm is
                    # therefore the legal narrow landing for dense horizontal
                    # terminal pitch.  Retained MCON stacks need 60 nm M1
                    # enclosure and are handled separately.
                    orientation = landing_orientations.get(center_nm)
                    legal_orientations = {
                        "narrow_x", "narrow_y",
                        "long_ne", "long_nw", "long_se", "long_sw",
                        "short_e", "short_w", "short_n", "short_s",
                        "dense_e", "dense_w", "dense_n", "dense_s",
                    }
                    if (
                        (width_nm, height_nm) in {(320, 320), (290, 230)}
                        and center_nm in via1_centers
                        and (
                            center_nm not in retained_mcon_centers
                            or orientation in {
                                "dense_e", "dense_w", "dense_n", "dense_s"
                            }
                        )
                        and orientation in legal_orientations
                    ):
                        cx_nm, cy_nm = center_nm
                        if orientation.startswith("dense_"):
                            # A 150 nm VIA1 needs 55 nm enclosure on every
                            # edge and 85 nm on two adjacent edges.  A retained
                            # 170 nm MCON needs 30 nm on every edge and 60 nm
                            # on two adjacent edges.  At a dense pin pair the
                            # 145/130 nm directional half-extents satisfy both
                            # rules while leaving exactly 140 nm between
                            # centres on a 400 nm pitch.  The orthogonal axis
                            # retains the original VIA1 landing extent.
                            side = orientation.removeprefix("dense_")
                            if side in {"e", "w"}:
                                new_lx_nm = cx_nm - (130 if side == "w" else 145)
                                new_rx_nm = cx_nm + (130 if side == "e" else 145)
                                new_by_nm, new_ty_nm = cy_nm - 160, cy_nm + 160
                            else:
                                new_lx_nm, new_rx_nm = cx_nm - 160, cx_nm + 160
                                new_by_nm = cy_nm - (130 if side == "s" else 145)
                                new_ty_nm = cy_nm + (130 if side == "n" else 145)
                        elif orientation.startswith("short_"):
                            side = orientation.removeprefix("short_")
                            new_lx_nm = cx_nm - (130 if side == "w" else 160)
                            new_rx_nm = cx_nm + (130 if side == "e" else 160)
                            new_by_nm = cy_nm - (130 if side == "s" else 160)
                            new_ty_nm = cy_nm + (130 if side == "n" else 160)
                        elif orientation.startswith("long_"):
                            quadrant = orientation.removeprefix("long_")
                            new_lx_nm = cx_nm - (160 if "w" in quadrant else 130)
                            new_rx_nm = cx_nm + (160 if "e" in quadrant else 130)
                            new_by_nm = cy_nm - (160 if "s" in quadrant else 130)
                            new_ty_nm = cy_nm + (160 if "n" in quadrant else 130)
                        else:
                            new_lx_nm, new_rx_nm = (
                                (cx_nm - 130, cx_nm + 130)
                                if orientation == "narrow_x"
                                else (round(lx * 1000), round(rx * 1000))
                            )
                            new_by_nm, new_ty_nm = (
                                (cy_nm - 130, cy_nm + 130)
                                if orientation == "narrow_y"
                                else (round(by * 1000), round(ty * 1000))
                            )
                        replacement: list[bytes] = []
                        for record in element:
                            if record_type(record) == XY:
                                points = (
                                    new_lx_nm, new_by_nm,
                                    new_rx_nm, new_by_nm,
                                    new_rx_nm, new_ty_nm,
                                    new_lx_nm, new_ty_nm,
                                    new_lx_nm, new_by_nm,
                                )
                                replacement.append(
                                    make_record(
                                        XY, INT4, struct.pack(">10i", *points)
                                    )
                                )
                            else:
                                replacement.append(record)
                        element = replacement
                        narrowed += 1
                if element_layer(element) == MET2:
                    lx, by, rx, ty = element_bbox(element, database_um)
                    center_nm = (
                        round((lx + rx) * 500),
                        round((by + ty) * 500),
                    )
                    width_nm = round((rx - lx) * 1000)
                    height_nm = round((ty - by) * 1000)
                    orientation = landing_orientations.get(center_nm, "")
                    if (
                        (width_nm, height_nm) == (320, 320)
                        and center_nm in via1_centers
                        and orientation in {
                            "dense_e", "dense_w", "dense_n", "dense_s"
                        }
                    ):
                        cx_nm, cy_nm = center_nm
                        side = orientation.removeprefix("dense_")
                        if side in {"e", "w"}:
                            new_lx_nm = cx_nm - (130 if side == "w" else 160)
                            new_rx_nm = cx_nm + (130 if side == "e" else 160)
                            new_by_nm, new_ty_nm = cy_nm - 160, cy_nm + 160
                        else:
                            new_lx_nm, new_rx_nm = cx_nm - 160, cx_nm + 160
                            new_by_nm = cy_nm - (130 if side == "s" else 160)
                            new_ty_nm = cy_nm + (130 if side == "n" else 160)
                        element = replace_boundary_bbox(
                            element,
                            (
                                new_lx_nm / 1000, new_by_nm / 1000,
                                new_rx_nm / 1000, new_ty_nm / 1000,
                            ),
                        )
                        narrowed += 1
                layer = element_layer(element) if element else None
                if layer in cuts_by_layer:
                    rectangles = boundary_rectangles(element, database_um)
                    original = list(rectangles)
                    for cut in cuts_by_layer[layer]:
                        rectangles = [
                            piece
                            for rectangle in rectangles
                            for piece in subtract_cut(rectangle, cut)
                        ]
                    if rectangles != original:
                        element = []
                        for rectangle in rectangles:
                            element.extend(rectangle_boundary(layer, rectangle))
                        clearance_trimmed += 1
                rewritten.extend(element)
            index = end + 1
        if not rewritten or record_type(rewritten[-1]) != ENDSTR:
            raise ValueError(f"{top}: malformed top structure")
        rewritten[-1:-1] = added
        rewritten_structures.append(rewritten)
    output = b"".join(header)
    output += b"".join(
        record for structure in rewritten_structures for record in structure
    )
    output += endlib
    return (
        output, removed, removed_m1_landings, narrowed, relocated_via1,
        relocated_mixer_via2_shapes, clearance_trimmed,
    )


def repair(
    source_path: Path,
    top: str,
    landing_orientations: dict[tuple[int, int], str] | None = None,
    landing_relocations: dict[tuple[int, int], tuple[int, int]] | None = None,
) -> tuple[bytes, dict[str, object]]:
    source = source_path.read_bytes()
    normalized, normalize_report = normalize(source)
    normalized, gate_bar_cells = remove_unused_trim_nfet_gate_bars(normalized)
    normalized, varactor_master_report = replace_varactor_master(normalized)
    normalized, legal_varactor_nwell_extended = extend_legal_varactor_nwell(
        normalized
    )
    normalized, overlay_mcons_removed = remove_power_overlay_bridge_mcons(
        normalized
    )
    structures, database_um = parse_gds(source_path)
    # Redundancy must be evaluated against the repaired child masters, not
    # the pre-repair source.  In particular, optional trim gate-bar M1/MCON
    # has just been removed and its routed contact must therefore be retained.
    with tempfile.NamedTemporaryFile(suffix=".gds") as repaired_children:
        repaired_children.write(normalized)
        repaired_children.flush()
        repaired_path = Path(repaired_children.name)
        native_m1 = child_rectangles(repaired_path, top, MET1)
        native_mcon = child_rectangles(repaired_path, top, MCON)
    redundant: set[tuple[int, int]] = set()
    mcon_centers: set[tuple[int, int]] = set()
    via1_centers: set[tuple[int, int]] = set()
    for layer, polygon in structures[top].polygons:
        if layer not in (MCON, VIA1):
            continue
        xs = [point[0] * database_um for point in polygon]
        ys = [point[1] * database_um for point in polygon]
        center = ((min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2)
        center_nm = (round(center[0] * 1000), round(center[1] * 1000))
        if layer == VIA1:
            via1_centers.add(center_nm)
        else:
            mcon_centers.add(center_nm)
            # These generated terminal stacks duplicate an already promoted
            # child access: either a native MCON is present or native child M1
            # already overlaps the routed landing.  The release gate must
            # still prove complete extracted terminal topology after removal;
            # geometry overlap alone is never accepted as signoff evidence.
            if (
                point_covered(center, native_m1)
                or point_covered(center, native_mcon)
            ):
                redundant.add(center_nm)
    retained_mcon = mcon_centers - redundant
    (
        output, removed, removed_m1_landings, narrowed, relocated,
        relocated_mixer_via2_shapes, clearance_trimmed,
    ) = filter_top_boundaries(
        normalized, top, database_um, redundant, via1_centers, retained_mcon,
        landing_orientations or {},
        landing_relocations or {},
    )
    if removed != len(redundant):
        raise ValueError(
            f"removed {removed} redundant MCON cuts, expected {len(redundant)}"
        )
    expected_mixer_via2 = len(mixer_via2_relocations())
    if relocated_mixer_via2_shapes != expected_mixer_via2:
        raise ValueError(
            "relocated "
            f"{relocated_mixer_via2_shapes} mixer VIA2 cuts, "
            f"expected {expected_mixer_via2}"
        )
    return output, {
        "status": "pass",
        "foundry_cell_normalization": normalize_report,
        "trim_nfet_unused_gate_bars_removed": gate_bar_cells,
        "varactor_master_normalization": varactor_master_report,
        "legal_varactor_nwell_extended": legal_varactor_nwell_extended,
        "redundant_power_overlay_mcons_removed": overlay_mcons_removed,
        "redundant_top_mcon_removed": removed,
        "redundant_top_m1_landings_removed": removed_m1_landings,
        "dense_via1_m1_landings_narrowed": narrowed,
        "dense_via1_landings_relocated": relocated,
        "mixer_via2_cuts_relocated": relocated_mixer_via2_shapes,
        "distinct_net_route_shoulders_trimmed": clearance_trimmed,
        "policy": (
            "remove only a duplicate generated terminal MCON whose center is "
            "covered by native child M1 or MCON; require post-repair extracted "
            "terminal-topology equivalence as an independent release gate"
        ),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("top")
    parser.add_argument("output", type=Path)
    parser.add_argument("--report", type=Path)
    parser.add_argument("--landing-plan", type=Path)
    parser.add_argument("--relocation-plan", type=Path)
    args = parser.parse_args()
    orientations: dict[tuple[int, int], str] = {}
    if args.landing_plan:
        plan = json.loads(args.landing_plan.read_text(encoding="utf-8"))
        orientations = {
            tuple(map(int, key.split(","))): str(value)
            for key, value in plan["m1_landing_orientation_by_center_nm"].items()
        }
    relocations: dict[tuple[int, int], tuple[int, int]] = {}
    if args.relocation_plan:
        plan = json.loads(args.relocation_plan.read_text(encoding="utf-8"))
        relocations = {
            tuple(map(int, key.split(","))): tuple(map(int, value))
            for key, value in plan["via1_relocation_nm_by_center_nm"].items()
        }
    output, report = repair(args.source, args.top, orientations, relocations)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_bytes(output)
    if args.report:
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
